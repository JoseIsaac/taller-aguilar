CREATE DATABASE IF NOT EXISTS taller_diesel CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_ai_ci;
USE taller_diesel;

CREATE TABLE IF NOT EXISTS app_user (
  id BIGINT PRIMARY KEY AUTO_INCREMENT,
  username VARCHAR(80) NOT NULL UNIQUE,
  password VARCHAR(255) NOT NULL,
  display_name VARCHAR(120) NOT NULL,
  role ENUM('ADMINISTRADOR','TALLER','OBSERVADOR') NOT NULL DEFAULT 'OBSERVADOR',
  active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS mechanic (
  id BIGINT PRIMARY KEY AUTO_INCREMENT,
  name VARCHAR(140) NOT NULL,
  kind ENUM('INTERNO','EXTERNO') NOT NULL DEFAULT 'INTERNO',
  specialty VARCHAR(140), phone VARCHAR(40), active BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE IF NOT EXISTS vehicle (
  id BIGINT PRIMARY KEY AUTO_INCREMENT,
  unit_number VARCHAR(50) NOT NULL UNIQUE,
  make VARCHAR(100), model VARCHAR(100), year INT, plate VARCHAR(30),
  odometer BIGINT, location VARCHAR(120), active BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE IF NOT EXISTS maintenance (
  id BIGINT PRIMARY KEY AUTO_INCREMENT,
  vehicle_id BIGINT NOT NULL,
  mechanic_id BIGINT,
  observation TEXT NOT NULL,
  status ENUM('TRABAJANDO','TERMINADO') NOT NULL DEFAULT 'TRABAJANDO',
  start_date DATE NOT NULL,
  end_date DATE,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_maintenance_vehicle FOREIGN KEY (vehicle_id) REFERENCES vehicle(id),
  CONSTRAINT fk_maintenance_mechanic FOREIGN KEY (mechanic_id) REFERENCES mechanic(id)
);

